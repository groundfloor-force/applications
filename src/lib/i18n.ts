const dictionaries: Record<Locale, Translations> = { en, fr }



export function getDictionary(locale: Locale): Translations {
  return dictionaries[locale] ?? dictionaries.en
}

// Simple template helper: replace {key} placeholders
export function tpl(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
}
